// 1. 숫자를 어떻게 쓰느냐가 타입을 정한다 ⭐ 제일 중요
//
//    7      (소수점 없음)  → int
//    7.0    (소수점만)     → double   ← M 없는 소수는 무조건 double!
//    7.0M   (M까지)        → decimal
//
//    이 표 하나로 이번 퀴즈 함정이 다 설명됨:
//    - Q5  double h = 7 / 2;      → int끼리 나눠서 3 (저장할 변수가 double이어도 계산은 먼저 int로 끝남)
//    - P3  (4 / 3)                → int끼리라 1 → 부피가 84.8로 나옴. 4.0 / 3.0 으로 써야 함
//    - Q8  decimal p = 19.99;     → 19.99는 double이라 decimal에 못 넣음 (CS0664). 19.99M
//    - P2  total * 0.9            → decimal × double 은 안 됨 (CS0019). 0.9M

// 2. double vs decimal
//
//    double  = 2진법 → 0.1 같은 수를 "대충 맞는 값"으로 저장
//    decimal = 10진법 → 0.1을 정확하게 저장
//
//    - 10진법에서 1/3 = 0.333... 이 끝이 없듯이, 2진법에서는 0.1이 끝이 없음
//      0.333 + 0.333 + 0.333 = 0.999 ≠ 1  이랑 같은 원리로
//      0.1 + 0.2 = 0.30000000000000004 ≠ 0.3  (그래서 Q7은 False, True)
//    - 정확한지 보는 법: 분수로 바꿔서 분모 보기
//      10진법은 분모가 2, 5로만 되어 있으면 정확 / 2진법은 분모가 2로만 되어 있으면 정확
//      0.5 = 1/2 → double도 정확 / 0.1 = 1/10 = 1/(2×5) → double은 부정확
//    - 몰라도 됨. 실무에서는 "돈이면 decimal" 만 기억하기
//    - Math.PI는 double → 원/구 계산은 double로 (decimal과 섞으면 에러)
//    - 섞어야 하면 직접 형변환: (decimal)19.99

// 3. 정수 나누기는 소수점 아래를 버린다
//
//    10 / 4 = 2 (2.5 아님) → Q2: 2 + 12 - 2 = 12
//    음수는 0 쪽으로 버림: -30 / 4 = -7.5 → -7 (-8 아님)

// 4. 오버플로 = 주행거리계
